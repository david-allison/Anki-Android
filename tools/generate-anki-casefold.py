"""Generate JVM case-folding data from Anki's pinned unicase 2.6.0 source.

Usage: python3 tools/generate-anki-casefold.py /path/to/unpacked/unicase-2.6.0
Requires rustc. Ordinary builds use the checked-in table and do not require Rust.
"""

import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import tempfile


def generate(crate: Path) -> str:
    unicode = crate.resolve() / "src/unicode"
    checksums = {
        "map.rs": "3679235bfd5ff68b0a0040bfe687fda231b1934762158bc52e6b58e2a1fcc6cb",
        "mod.rs": "d6183755af22f1f74c63b27ae2b779071030f70358923b4c73010276e492d16b",
    }
    for name, expected in checksums.items():
        if hashlib.sha256((unicode / name).read_bytes()).hexdigest() != expected:
            raise ValueError(f"{name} differs from Anki's pinned unicase 2.6.0 source")

    source = (unicode / "mod.rs").read_text()
    # Run the original iterator, including its three-character expansion-order bug.
    fold = source[source.index("mod fold {"):source.index("#[cfg(test)]")]
    program = fold + '\n#[path = ' + json.dumps(str(unicode / "map.rs"), ensure_ascii=False) + '] mod map;\n'
    program += r"""
fn main() {
    for cp in 0..=0x10ffff {
        if let Some(c) = char::from_u32(cp) {
            let folded: String = map::lookup(c).collect();
            if folded != c.to_string() {
                println!("{:X};{}", cp, folded.chars()
                    .map(|c| format!("{:X}", c as u32)).collect::<Vec<_>>().join(" "));
            }
        }
    }
}
"""
    with tempfile.TemporaryDirectory(prefix="ankidroid-casefold-") as directory:
        rust = Path(directory) / "casefold.rs"
        executable = Path(directory) / "casefold"
        rust.write_text(program)
        subprocess.run(["rustc", "--edition=2021", "-Awarnings", str(rust), "-o", str(executable)], check=True)
        output = subprocess.check_output([str(executable)], text=True)

    mappings = {
        int(key, 16): [int(cp, 16) for cp in value.split()]
        for key, value in (line.split(";") for line in output.splitlines())
    }
    singles = [(cp, folded[0] - cp) for cp, folded in mappings.items() if len(folded) == 1]
    exceptions = {cp: folded for cp, folded in mappings.items() if len(folded) != 1}
    ranges = []
    index = 0
    while index < len(singles):
        first, delta = singles[index]
        end = index + 1
        step = singles[end][0] - first if end < len(singles) else 0
        if step in (1, 2):
            while end < len(singles) and singles[end] == (first + (end - index) * step, delta):
                end += 1
        if end - index >= 3:
            ranges.append((first, singles[end - 1][0], step, delta))
            index = end
        else:
            exceptions[first] = [first + delta]
            index += 1

    expanded = {cp: [cp + delta] for first, last, step, delta in ranges for cp in range(first, last + 1, step)}
    expanded.update(exceptions)
    assert expanded == mappings, "Compression changed the upstream mappings"
    assert all(left[1] < right[0] for left, right in zip(ranges, ranges[1:])), "Overlapping ranges"

    def hexadecimal(number: int) -> str:
        return ("-" if number < 0 else "") + f"0x{abs(number):04X}"

    def escaped(code_points: list[int]) -> str:
        encoded = "".join(chr(cp) for cp in code_points).encode("utf-16-be")
        return "".join(f"\\u{int.from_bytes(encoded[i:i + 2], 'big'):04X}" for i in range(0, len(encoded), 2))

    license_text = (crate / "LICENSE-MIT").read_text().strip()
    lines = [
        "//noinspection MissingCopyrightHeader MIT; upstream copyright and license are preserved below.",
        "// SPDX-License-Identifier: MIT",
        "/*", license_text, "*/", "",
        "// Generated by tools/generate-anki-casefold.py from unicase 2.6.0. Do not edit.",
        "package com.ichi2.anki.common.utils", "",
        "internal object Unicase26Data {",
        "    // Each range contains first, last, step, and the offset to the folded code point.",
        "    val ranges =", "        arrayOf(",
    ]
    lines.extend("            intArrayOf(" + ", ".join(map(hexadecimal, row)) + ")," for row in ranges)
    lines.extend(["        )", "", "    val exceptions =", "        mapOf("])
    lines.extend(f'            {hexadecimal(cp)} to "{escaped(folded)}",' for cp, folded in sorted(exceptions.items()))
    lines.extend(["        )", "}", ""])
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("unicase_source", type=Path)
    parser.add_argument("--check", action="store_true", help="Check the committed table without rewriting it")
    arguments = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    target = root / "common/src/main/java/com/ichi2/anki/common/utils/Unicase26Data.kt"
    notice = root / "common/src/main/resources/META-INF/anki/unicase-2.6.0.LICENSE"
    license_text = (arguments.unicase_source / "LICENSE-MIT").read_text().rstrip() + "\n"
    generated = generate(arguments.unicase_source)
    if arguments.check:
        if target.read_text() != generated:
            raise SystemExit("Case-folding table differs; regenerate it with this script")
        if notice.read_text() != license_text:
            raise SystemExit("Packaged case-folding license differs from upstream")
    else:
        target.write_text(generated)
        notice.parent.mkdir(parents=True, exist_ok=True)
        notice.write_text(license_text)


if __name__ == "__main__":
    main()
